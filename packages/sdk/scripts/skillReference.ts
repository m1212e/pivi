// Renders the generated half of the pivi-app skill: references/protocol.md, the
// protocol as a compact, readable reference built from the same schemas the
// host validates with, so it cannot drift. `bun run skill` writes it and
// test/skill.spec.ts fails when the committed copy is stale.
import { buildProtocolDocument } from '../src/schema';

type Schema = {
	type?: string | string[];
	properties?: Record<string, Schema>;
	required?: string[];
	items?: Schema;
	enum?: unknown[];
	const?: unknown;
	oneOf?: Schema[];
	anyOf?: Schema[];
	$ref?: string;
	$defs?: Record<string, Schema>;
	additionalProperties?: Schema | boolean;
};

const pad = (depth: number) => '  '.repeat(depth);

/** A JSON Schema as the TypeScript type an app would write. */
function render(schema: Schema, names: Record<string, string>, depth = 0): string {
	if (schema.$ref) return names[schema.$ref.split('/').pop() ?? ''] ?? 'unknown';
	if (schema.const !== undefined) return JSON.stringify(schema.const);
	if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
	const union = schema.oneOf ?? schema.anyOf;
	if (union) return union.map((s) => render(s, names, depth)).join(' | ');
	switch (schema.type) {
		case 'string':
			return 'string';
		case 'number':
		case 'integer':
			return 'number';
		case 'boolean':
			return 'boolean';
		case 'null':
			return 'null';
		case 'array': {
			const item = render(schema.items ?? {}, names, depth);
			return /[|{]/.test(item) ? `(${item})[]` : `${item}[]`;
		}
		case 'object': {
			const entries = Object.entries(schema.properties ?? {});
			if (entries.length === 0) return '{}';
			const required = new Set(schema.required ?? []);
			const lines = entries.map(
				([key, value]) =>
					`${pad(depth + 1)}${key}${required.has(key) ? '' : '?'}: ${render(value, names, depth + 1)};`
			);
			return `{\n${lines.join('\n')}\n${pad(depth)}}`;
		}
		default:
			return 'unknown';
	}
}

const block = (code: string) => '```ts\n' + code + '\n```';

type ProtocolDocument = ReturnType<typeof buildProtocolDocument>;
type MethodDoc = ProtocolDocument['methods'][number];

const featureOf = (m: MethodDoc) => ('feature' in m && m.feature ? m.feature : undefined);

function header(doc: ProtocolDocument): string[] {
	return [
		'<!-- Generated by packages/sdk/scripts/skillReference.ts from the protocol schemas. Do not edit. -->',
		`# pivi app protocol, version ${doc.protocol}`,
		'',
		doc.transport,
		'',
		`Features an app can declare in its manifest: ${doc.features.map((f) => `\`${f}\``).join(', ')}.`,
		'The host only sends a request or notification whose feature the manifest declares, and drops',
		'what an app sends without declaring its feature. Methods without a feature are always on.',
		'',
		'Every message is validated on arrival, so respect the size caps in `src/limits.ts`.',
		''
	];
}

function overview(doc: ProtocolDocument): string[] {
	const rows = doc.methods.map((m) => {
		const feature = featureOf(m) ? `\`${featureOf(m)}\`` : 'always';
		return `| \`${m.method}\` | ${m.from} → ${m.from === 'app' ? 'host' : 'app'} | ${m.kind} | ${feature} |`;
	});
	return [
		'## Overview',
		'',
		'| Method | Direction | Kind | Feature |',
		'| --- | --- | --- | --- |',
		...rows,
		'',
		'In `defineApp`, notifications and requests from the host are handlers, and the app → host',
		'notifications are methods of the returned context.',
		''
	];
}

/** A params or result schema as TypeScript, with the recursive UI tree named `UiNode`. */
function typeBlock(label: string, schema: Schema): string[] {
	const names = Object.fromEntries(Object.keys(schema.$defs ?? {}).map((k) => [k, 'UiNode']));
	const defs = Object.entries(schema.$defs ?? {}).map(
		([key, def]) => `type ${names[key]} =\n  ${render(def, names, 1)}`
	);
	return [
		`${label}:`,
		'',
		block([`type ${label} = ${render(schema, names)}`, ...defs].join('\n\n')),
		''
	];
}

function methodSection(m: MethodDoc): string[] {
	const feature = featureOf(m) ? `, feature \`${featureOf(m)}\`` : '';
	const out = [
		`### \`${m.method}\``,
		'',
		`From ${m.from}, ${m.kind}${feature}. ${m.description}`,
		''
	];
	if (m.params) out.push(...typeBlock('Params', m.params as Schema));
	if (m.result) out.push(...typeBlock('Result', m.result as Schema));
	return out;
}

export function renderProtocolReference(): string {
	const doc = buildProtocolDocument();
	const out = [
		...header(doc),
		...overview(doc),
		'## Methods',
		'',
		...doc.methods.flatMap(methodSection)
	];
	return (
		out
			.join('\n')
			.replace(/\n{3,}/g, '\n\n')
			.trimEnd() + '\n'
	);
}
